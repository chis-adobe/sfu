/**
 * Builds the importer's faculty list from the AEM FacultyList persisted query.
 * Each faculty content fragment is matched (by title) to its link on the sfu.ca
 * Faculties page, which gives the page slug and the source page to import.
 *
 * Writes lib/sfu-faculties.js and urls-faculty-majors.txt (run from the repo root):
 *   node tools/importer/fetch-faculties.mjs
 * The majors are not stored: the Majors block loads them live per faculty.
 */
import { writeFileSync } from 'node:fs';

const GRAPHQL = 'https://publish-p130746-e1275972.adobeaemcloud.com/graphql/execute.json/ref-demo-eds';
const SOURCE = 'https://www.sfu.ca/students/admission/programs/faculties.html';

const list = await (await fetch(`${GRAPHQL}/FacultyList`)).json();
const items = list?.data?.facultyList?.items;
if (!Array.isArray(items) || !items.length) throw new Error('FacultyList returned no faculties');

const html = await (await fetch(SOURCE)).text();
const decode = (s) => s.replace(/&amp;/g, '&').replace(/&#39;|&rsquo;/g, "'").replace(/\s+/g, ' ').trim();
const links = [...html.matchAll(/<a href="(\/students\/admission\/programs\/[^"]+)"[^>]*>([^<]+)<\/a>/g)]
  .map(([, href, label]) => ({ href, label: decode(label) }));

const faculties = items.map(({ _path: path, title }) => {
  const source = links.find((l) => l.label === title);
  const slug = source?.href.match(/\/programs\/([^/.]+)/)?.[1]
    || path.split('/').pop().replace(/^faculty-of-/, '');
  return {
    title,
    path,
    slug,
    source: source ? new URL(source.href, SOURCE).href : null,
  };
});

writeFileSync(new URL('./lib/sfu-faculties.js', import.meta.url), `/* eslint-disable */
// Generated by tools/importer/fetch-faculties.mjs from the AEM FacultyList persisted query.
// title / path come from the faculty content fragments; slug and source from sfu.ca.

/** Faculty content fragments: [{ title, path, slug, source }] */
export const FACULTIES = ${JSON.stringify(faculties, null, 2)};

export const FACULTIES_PAGE = { source: '${SOURCE}', path: '/faculties' };

/** EDS path of a faculty's majors page. */
export const facultyPagePath = (faculty) => \`/faculties/\${faculty.slug}\`;
`);
writeFileSync(new URL('./urls-faculty-majors.txt', import.meta.url),
  `${faculties.filter((f) => f.source).map((f) => f.source).join('\n')}\n`);
faculties.forEach((f) => console.log(`${f.title} -> /faculties/${f.slug} (${f.source || 'no sfu.ca page'})`));
